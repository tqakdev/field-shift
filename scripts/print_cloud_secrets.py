#!/usr/bin/env python3
"""Write a Streamlit Cloud–ready secrets.toml from secrets/ee-key.json.

Output path: secrets/cloud_secrets.toml (under git-ignored secrets/).
Never prints secret values to the terminal — only a short status line.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_KEY = REPO_ROOT / "secrets" / "ee-key.json"
DEFAULT_OUT = REPO_ROOT / "secrets" / "cloud_secrets.toml"


def build_cloud_secrets_toml(key_path: Path) -> str:
    """Build TOML with EE_* keys and inlined service-account JSON.

    Parameters
    ----------
    key_path:
        Path to the Google service-account JSON file.
    """
    data = json.loads(key_path.read_text(encoding="utf-8"))
    email = str(data.get("client_email", "")).strip()
    project = str(data.get("project_id", "")).strip()
    if not email or not project:
        raise ValueError("Key file missing client_email or project_id")

    # Compact one-line JSON is safest inside TOML; pretty indent also works.
    # Use dumps so private_key newlines become \\n escapes inside the JSON string.
    inline_json = json.dumps(data, indent=2, ensure_ascii=False)

    return (
        "# Generated by scripts/print_cloud_secrets.py — DO NOT COMMIT\n"
        "# Paste into Streamlit Community Cloud → App settings → Secrets\n"
        f'EE_SERVICE_ACCOUNT = "{email}"\n'
        f'EE_PROJECT = "{project}"\n'
        f'EE_PRIVATE_KEY_JSON = """\n{inline_json}\n"""\n'
    )


def main(argv: list[str] | None = None) -> int:
    """Write secrets/cloud_secrets.toml; print only non-secret status."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--key", type=Path, default=DEFAULT_KEY)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)

    if not args.key.is_file():
        print(
            "ERROR: service-account key file not found under secrets/",
            file=sys.stderr,
        )
        return 1

    try:
        text = build_cloud_secrets_toml(args.key)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"ERROR: could not build secrets ({type(exc).__name__})", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    # Status only — no paths that embed key material, no secret contents
    print("Wrote secrets/cloud_secrets.toml (git-ignored). Open that file to copy-paste.")
    print("Keys: EE_SERVICE_ACCOUNT, EE_PROJECT, EE_PRIVATE_KEY_JSON (values not shown).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
