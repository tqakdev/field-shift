#!/usr/bin/env python3
"""Build .streamlit/secrets.toml from secrets/ee-key.json (never prints secret values).

Local secrets.toml stores a *path* to the key file (not the key body) so CLI tools and
Streamlit both work without embedding private key material in TOML. For Streamlit
Community Cloud, paste the JSON body using .streamlit/secrets.toml.example as a template.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_KEY = REPO_ROOT / "secrets" / "ee-key.json"
DEFAULT_OUT = REPO_ROOT / ".streamlit" / "secrets.toml"


def build_secrets_toml(key_path: Path) -> str:
    """Return secrets.toml text referencing the key file path (not key contents)."""
    data = json.loads(key_path.read_text(encoding="utf-8"))
    email = data.get("client_email", "")
    project = data.get("project_id", "")
    if not email or not project:
        raise ValueError("Key file missing client_email or project_id")

    resolved = key_path.resolve()
    return (
        "# Generated by scripts/make_secrets.py — DO NOT COMMIT\n"
        "# Local: EE_PRIVATE_KEY_JSON is a filesystem path. "
        "On Streamlit Cloud, paste the JSON object instead "
        "(see .streamlit/secrets.toml.example).\n"
        f'EE_SERVICE_ACCOUNT = "{email}"\n'
        f'EE_PROJECT = "{project}"\n'
        f'EE_PRIVATE_KEY_JSON = "{resolved}"\n'
    )


def main(argv: list[str] | None = None) -> int:
    """CLI entry: write .streamlit/secrets.toml and print only status (no secrets)."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--key", type=Path, default=DEFAULT_KEY, help="Service account JSON path")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Output secrets.toml path")
    args = parser.parse_args(argv)

    if not args.key.is_file():
        print("ERROR: key file not found at expected path under secrets/", file=sys.stderr)
        return 1

    text = build_secrets_toml(args.key)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"Wrote {args.out.relative_to(REPO_ROOT)} (path-based; values redacted)")
    print("Keys present: EE_SERVICE_ACCOUNT, EE_PROJECT, EE_PRIVATE_KEY_JSON")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
